"""Generates the MoneyMate launcher icons from one vector design.

The design (wallet with a rising bar chart and a gold coin clasp on deep
navy) is defined once below in a 108 x 108 grid, the Android adaptive icon
canvas. From it this script writes:

* assets/branding/app_icon.svg and app_icon_foreground.svg (masters)
* Android adaptive icon (vector foreground, background and themed
  monochrome layer) plus legacy PNG mipmaps
* iOS AppIcon set, macOS AppIcon set and web icons (PNG)

PNGs are rasterised by headless Microsoft Edge / Chrome straight from the
vector at each target size, so no Python packages or Flutter dependencies
are needed. Run from the project root:

    python tool/generate_app_icons.py
"""

import base64
import json
import os
import re
import shutil
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ------------------------------------------------------------------ palette
NAVY_TOP = '#13294B'
NAVY_BOTTOM = '#0A1628'
NAVY_INK = '#0B1A30'  # cut-out details (bars, clasp)
GREEN_LIGHT = '#2EE6A8'
GREEN_DARK = '#0FA36F'
MINT = '#B7F7DC'
GOLD = '#F7B940'

# ------------------------------------------------------------------ geometry
# All in the 108-unit adaptive canvas; the 66-unit safe zone is centred.
BANKNOTE = dict(x=33, y=30, w=40, h=22, r=4, rotate=-7, cx=53, cy=41)
BODY = dict(x=27, y=40, w=54, h=37, r=9)
CLASP = dict(x=62, y=50, w=24, h=17, r=8.5)
COIN = dict(cx=73.5, cy=58.5, r=4.2)
BARS = [  # x, top; all share width and bottom
    (35, 62),
    (43, 56.5),
    (51, 50.5),
]
BAR_W = 5
BAR_BOTTOM = 70


def rounded_rect_path(x, y, w, h, r):
    """SVG / VectorDrawable path data for a rounded rectangle."""
    return (
        f'M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} '
        f'V{y + h - r} A{r},{r} 0 0 1 {x + w - r},{y + h} '
        f'H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} '
        f'V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z'
    )


def bar_paths():
    return [
        rounded_rect_path(x, top, BAR_W, BAR_BOTTOM - top, BAR_W / 2)
        for x, top in BARS
    ]


def circle_path(cx, cy, r):
    return (
        f'M{cx - r},{cy} A{r},{r} 0 1 0 {cx + r},{cy} '
        f'A{r},{r} 0 1 0 {cx - r},{cy} Z'
    )


BANKNOTE_PATH = rounded_rect_path(
    BANKNOTE['x'], BANKNOTE['y'], BANKNOTE['w'], BANKNOTE['h'], BANKNOTE['r']
)
BODY_PATH = rounded_rect_path(**BODY)
CLASP_PATH = rounded_rect_path(**CLASP)
COIN_PATH = circle_path(**COIN)


# ----------------------------------------------------------------------- SVG
def svg_foreground_elements():
    b = BANKNOTE
    bars = ''.join(f'<path d="{p}" fill="{NAVY_INK}"/>' for p in bar_paths())
    return (
        f'<g transform="rotate({b["rotate"]} {b["cx"]} {b["cy"]})">'
        f'<path d="{BANKNOTE_PATH}" fill="{MINT}"/>'
        f'<path d="M{b["x"] + 6},{b["y"] + 6} H{b["x"] + 20}" '
        f'stroke="{GREEN_DARK}" stroke-width="2.4" stroke-linecap="round" '
        f'opacity="0.55"/>'
        f'</g>'
        f'<path d="{BODY_PATH}" fill="url(#body)"/>'
        f'{bars}'
        f'<path d="{CLASP_PATH}" fill="{NAVY_INK}"/>'
        f'<path d="{COIN_PATH}" fill="{GOLD}"/>'
    )


SVG_DEFS = (
    '<defs>'
    f'<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
    f'<stop offset="0" stop-color="{NAVY_TOP}"/>'
    f'<stop offset="1" stop-color="{NAVY_BOTTOM}"/></linearGradient>'
    f'<linearGradient id="body" x1="0" y1="0" x2="0" y2="1">'
    f'<stop offset="0" stop-color="{GREEN_LIGHT}"/>'
    f'<stop offset="1" stop-color="{GREEN_DARK}"/></linearGradient>'
    '</defs>'
)


def svg_icon(size, *, background=True, corner_radius=0.0, zoom=1.0):
    """Full icon. [zoom] enlarges the artwork about the centre (the adaptive
    canvas keeps a wide margin that other platforms do not need)."""
    side = 108 / zoom
    offset = (108 - side) / 2
    bg = ''
    if background:
        r = corner_radius * side
        bg = (
            f'<rect x="{offset}" y="{offset}" width="{side}" height="{side}" '
            f'rx="{r}" fill="url(#bg)"/>'
        )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" '
        f'height="{size}" viewBox="{offset} {offset} {side} {side}">'
        f'{SVG_DEFS}{bg}{svg_foreground_elements()}</svg>'
    )


# ------------------------------------------------------ Android vector XML
def vd(body):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/generate_app_icons.py. Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f'{body}'
        '</vector>\n'
    )


def vd_gradient_path(path, top, bottom, y0, y1):
    return (
        f'    <path android:pathData="{path}">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear"\n'
        f'                android:startX="54" android:startY="{y0}"\n'
        f'                android:endX="54" android:endY="{y1}">\n'
        f'                <item android:offset="0" android:color="{top}"/>\n'
        f'                <item android:offset="1" android:color="{bottom}"/>\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n'
    )


def android_foreground():
    b = BANKNOTE
    body = (
        f'    <group android:pivotX="{b["cx"]}" android:pivotY="{b["cy"]}"\n'
        f'        android:rotation="{b["rotate"]}">\n'
        f'        <path android:fillColor="{MINT}"\n'
        f'            android:pathData="{BANKNOTE_PATH}"/>\n'
        f'        <path android:strokeColor="{GREEN_DARK}"\n'
        '            android:strokeAlpha="0.55" android:strokeWidth="2.4"\n'
        '            android:strokeLineCap="round"\n'
        f'            android:pathData="M{b["x"] + 6},{b["y"] + 6} '
        f'H{b["x"] + 20}"/>\n'
        '    </group>\n'
    )
    body += vd_gradient_path(
        BODY_PATH, GREEN_LIGHT, GREEN_DARK, BODY['y'], BODY['y'] + BODY['h']
    )
    for p in bar_paths():
        body += f'    <path android:fillColor="{NAVY_INK}" android:pathData="{p}"/>\n'
    body += (
        f'    <path android:fillColor="{NAVY_INK}" android:pathData="{CLASP_PATH}"/>\n'
        f'    <path android:fillColor="{GOLD}" android:pathData="{COIN_PATH}"/>\n'
    )
    return vd(body)


def android_background():
    return vd(
        vd_gradient_path('M0,0 H108 V108 H0 Z', NAVY_TOP, NAVY_BOTTOM, 0, 108)
    )


def android_monochrome():
    """Themed icon (Android 13+): one colour, details cut out."""
    b = BANKNOTE
    cutout = ' '.join([BODY_PATH, *bar_paths(), CLASP_PATH])
    return vd(
        f'    <group android:pivotX="{b["cx"]}" android:pivotY="{b["cy"]}"\n'
        f'        android:rotation="{b["rotate"]}">\n'
        '        <path android:fillColor="#FFFFFFFF" android:fillAlpha="0.6"\n'
        f'            android:pathData="{BANKNOTE_PATH}"/>\n'
        '    </group>\n'
        '    <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd"\n'
        f'        android:pathData="{cutout}"/>\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{COIN_PATH}"/>\n'
    )


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""


# ----------------------------------------------------------- rasterising
def find_browser():
    candidates = [
        r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe',
        r'C:\Program Files\Microsoft\Edge\Application\msedge.exe',
        r'C:\Program Files\Google\Chrome\Application\chrome.exe',
        '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
        shutil.which('google-chrome') or '',
        shutil.which('chromium') or '',
    ]
    for c in candidates:
        if c and os.path.exists(c):
            return c
    raise SystemExit('Microsoft Edge or Google Chrome is needed to render PNGs.')


def rasterise(jobs):
    """jobs: list of (svg_text, size, output_path). Renders all of them in
    one headless browser run by drawing each SVG onto a canvas."""
    items = [
        {
            'src': 'data:image/svg+xml;base64,'
            + base64.b64encode(svg.encode()).decode(),
            'size': size,
        }
        for svg, size, _ in jobs
    ]
    html = (
        '<!doctype html><html><body><pre id="out"></pre><script>'
        f'const items = {json.dumps(items)};'
        'Promise.all(items.map(it => new Promise(done => {'
        '  const img = new Image();'
        '  img.onload = () => {'
        '    const c = document.createElement("canvas");'
        '    c.width = c.height = it.size;'
        '    const g = c.getContext("2d");'
        '    g.imageSmoothingQuality = "high";'
        '    g.drawImage(img, 0, 0, it.size, it.size);'
        '    done(c.toDataURL("image/png"));'
        '  };'
        '  img.src = it.src;'
        '}))).then(urls => {'
        '  document.getElementById("out").textContent = urls.join("\\n");'
        '});'
        '</script></body></html>'
    )
    tmp = tempfile.mkdtemp(prefix='icons_')
    page = os.path.join(tmp, 'render.html')
    with open(page, 'w', encoding='utf-8') as f:
        f.write(html)
    out = subprocess.run(
        [
            find_browser(),
            '--headless=new',
            '--disable-gpu',
            f'--user-data-dir={os.path.join(tmp, "profile")}',
            '--virtual-time-budget=10000',
            '--dump-dom',
            'file:///' + page.replace('\\', '/'),
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    urls = re.findall(r'data:image/png;base64,([A-Za-z0-9+/=]+)', out)
    if len(urls) != len(jobs):
        raise SystemExit(f'Rendered {len(urls)} of {len(jobs)} icons.')
    for data, (_, _, path) in zip(urls, jobs):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as f:
            f.write(base64.b64decode(data))
    shutil.rmtree(tmp, ignore_errors=True)


def strip_alpha(path):
    """Rewrites an opaque 8-bit RGBA PNG as RGB (App Store icons must not
    have an alpha channel). Pure Python: zlib + the PNG filter rules."""
    import struct
    import zlib

    with open(path, 'rb') as f:
        data = f.read()
    pos, idat, header = 8, b'', None
    while pos < len(data):
        length, kind = struct.unpack('>I4s', data[pos:pos + 8])
        chunk = data[pos + 8:pos + 8 + length]
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', chunk)
        elif kind == b'IDAT':
            idat += chunk
        pos += 12 + length
    width, height, depth, color, _, _, interlace = header
    if color == 2:
        return
    assert depth == 8 and color == 6 and interlace == 0, header
    raw = zlib.decompress(idat)
    bpp, stride = 4, width * 4
    prev = bytearray(stride)
    out = bytearray()
    i = 0
    for _ in range(height):
        ftype = raw[i]
        line = bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 0xFF
            elif ftype == 2:
                line[x] = (line[x] + b) & 0xFF
            elif ftype == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pred) & 0xFF
        out.append(0)
        for x in range(0, stride, 4):
            if line[x + 3] != 255:
                raise SystemExit(f'{path} is not opaque.')
            out += line[x:x + 3]
        prev = line

    def chunk(kind, body):
        return (
            struct.pack('>I', len(body)) + kind + body
            + struct.pack('>I', zlib.crc32(kind + body) & 0xFFFFFFFF)
        )

    png = (
        b'\x89PNG\r\n\x1a\n'
        + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
        + chunk(b'IDAT', zlib.compress(bytes(out), 9))
        + chunk(b'IEND', b'')
    )
    with open(path, 'wb') as f:
        f.write(png)


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main():
    p = lambda *parts: os.path.join(ROOT, *parts)  # noqa: E731

    # Masters.
    write('assets/branding/app_icon.svg', svg_icon(1024, zoom=1.18))
    write(
        'assets/branding/app_icon_foreground.svg',
        svg_icon(432, background=False),
    )

    # Android adaptive icon (API 26+): vector layers, sharp at any size.
    res = 'android/app/src/main/res'
    write(f'{res}/drawable/ic_launcher_foreground.xml', android_foreground())
    write(f'{res}/drawable/ic_launcher_background.xml', android_background())
    write(f'{res}/drawable/ic_launcher_monochrome.xml', android_monochrome())
    write(f'{res}/mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE_XML)
    write(f'{res}/mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE_XML)

    jobs = []
    # Android legacy icons (API < 26): rounded square and circle.
    for density, size in {
        'mdpi': 48,
        'hdpi': 72,
        'xhdpi': 96,
        'xxhdpi': 144,
        'xxxhdpi': 192,
    }.items():
        jobs.append((
            svg_icon(size, corner_radius=0.22, zoom=1.2),
            size,
            p(res, f'mipmap-{density}', 'ic_launcher.png'),
        ))
        jobs.append((
            svg_icon(size, corner_radius=0.5, zoom=1.2),
            size,
            p(res, f'mipmap-{density}', 'ic_launcher_round.png'),
        ))

    # iOS: opaque, square (the system applies the mask).
    ios_dir = p('ios', 'Runner', 'Assets.xcassets', 'AppIcon.appiconset')
    with open(os.path.join(ios_dir, 'Contents.json'), encoding='utf-8') as f:
        contents = json.load(f)
    for image in contents['images']:
        name = image.get('filename')
        if not name:
            continue
        base = float(image['size'].split('x')[0])
        scale = int(image['scale'].rstrip('x'))
        size = round(base * scale)
        jobs.append((svg_icon(size, zoom=1.18), size, os.path.join(ios_dir, name)))

    # macOS: rounded square with transparent margin, per Apple's grid.
    mac_dir = p('macos', 'Runner', 'Assets.xcassets', 'AppIcon.appiconset')
    for size in (16, 32, 64, 128, 256, 512, 1024):
        jobs.append((
            svg_icon(size, corner_radius=0.18, zoom=0.98),
            size,
            os.path.join(mac_dir, f'app_icon_{size}.png'),
        ))

    # Web.
    for size in (192, 512):
        jobs.append((
            svg_icon(size, corner_radius=0.22, zoom=1.2),
            size,
            p('web', 'icons', f'Icon-{size}.png'),
        ))
        jobs.append((
            svg_icon(size),
            size,
            p('web', 'icons', f'Icon-maskable-{size}.png'),
        ))
    jobs.append((svg_icon(32, corner_radius=0.22, zoom=1.2), 32, p('web', 'favicon.png')))

    rasterise(jobs)
    for _, _, path in jobs:
        if path.startswith(ios_dir):
            strip_alpha(path)
    print(f'Wrote {len(jobs)} PNGs and the Android vector layers.')


if __name__ == '__main__':
    main()
